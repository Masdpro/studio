/**
 * Ready-made product lists for the vendor "Quick add" flow: business type → group → products.
 * Vendors tick what they sell, add their price, and can list straight away with the catalog photo
 * (or swap in their own). Names and descriptions are starting points; vendors can edit them.
 *
 * Catalog photos live in /public/catalog/<slug>.webp and are listed in catalog-images.json with
 * their licence and credit (see /credits). Items without a catalog photo need the vendor's own.
 */
import catalogImages from './catalog-images.json';

export type CatalogItem = { name: string; description: string; slug: string; image?: string };
export type CatalogGroup = { id: string; label: string; items: CatalogItem[] };
export type BusinessType = { id: string; label: string; blurb: string; icon: string; groups: CatalogGroup[] };
export type ImageCredit = { title: string; creator: string; license: string; source: string };

export const CATALOG_IMAGES = catalogImages as Record<string, ImageCredit>;

export const slugify = (s: string) =>
  s
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 70);

/** Path of the catalog photo for a product name, if we have one. */
export const catalogImageFor = (name: string) => {
  const slug = slugify(name);
  return CATALOG_IMAGES[slug] ? `/catalog/${slug}.webp` : undefined;
};

/** [name, description, image search hint (used only by scripts/catalog-images)] */
type Row = [string, string, string?];

const g = (id: string, label: string, rows: Row[]): CatalogGroup => ({
  id,
  label,
  items: rows.map(([name, description]) => {
    const slug = slugify(name);
    return { name, description, slug, image: CATALOG_IMAGES[slug] ? `/catalog/${slug}.webp` : undefined };
  }),
});

