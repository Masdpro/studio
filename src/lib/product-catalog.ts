export const BUSINESS_TYPES: BusinessType[] = RAW.map((t) => ({
  id: t.id,
  label: t.label,
  blurb: t.blurb,
  icon: t.icon,
  groups: t.groups.map(([id, label, rows]) => g(id, label, rows)),
}));

/** Every catalog product with where it sits, for the search box at the top of Quick add. */
export const ALL_CATALOG_ITEMS = BUSINESS_TYPES.flatMap((t) =>
  t.groups.flatMap((grp) => grp.items.map((item) => ({ ...item, typeId: t.id, groupId: grp.id, groupLabel: grp.label }))),
);

/** For scripts/catalog-images: every product with its image search hint. */
export const CATALOG_IMAGE_HINTS = RAW.flatMap((t) => t.groups.flatMap(([, , rows]) => rows.map(([name, , hint]) => ({ slug: slugify(name), name, hint: hint ?? name }))));

export function getBusinessType(id: string | null | undefined): BusinessType | undefined {
  return BUSINESS_TYPES.find((t) => t.id === id);
}
